pub fn blueprint_by_domain_id(domain_id: &str) -> Option<DomainBlueprint> {
    ALL_19_BLUEPRINTS
        .iter()
        .copied()
        .find(|b| b.domain_id.eq_ignore_ascii_case(domain_id))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::eval_nn::domains::contains_forbidden_raw_gov_id_digits;
    use lv_agent::gates::check_citizen_text;
    use lv_domain::registry::DomainPackRegistry;
    use std::collections::BTreeSet;

    #[test]
    fn all_19_blueprints_match_lv_domain_registry_and_citizen_hygiene() {
        let reg = DomainPackRegistry::builtin_18();
        assert_eq!(ALL_19_BLUEPRINTS.len(), 19);

        let mut seen_domains = BTreeSet::new();
        let mut seen_packs = BTreeSet::new();
        for bp in &ALL_19_BLUEPRINTS {
            assert!(seen_domains.insert(bp.domain_id), "duplicate domain {}", bp.domain_id);
            assert!(seen_packs.insert(bp.pack_id), "duplicate pack {}", bp.pack_id);
            if bp.domain_id != "XRC-TWIN" {
                let meta = reg
                    .get(bp.domain_id)
                    .unwrap_or_else(|| panic!("missing registry pack for {}", bp.domain_id));
                assert_eq!(meta.id, bp.pack_id, "pack_id mismatch on {}", bp.domain_id);
                assert_eq!(
                    meta.required_fields, bp.required_field_keys,
                    "required_fields mismatch on {}",
                    bp.domain_id
                );
            }
            assert!(bp.domain_signature_terms.len() >= 6);
            let combined = format!(
                "{} {} {} {} {} {} {} {}",
                bp.doc_category_ko,
                bp.doc_category_en,
                bp.governing_statute,
                bp.statutory_clauses.join(" "),
                bp.line_item_templates
                    .iter()
                    .map(|(a, b, c)| format!("{a} {b} {c}"))
                    .collect::<Vec<_>>()
                    .join(" "),
                bp.domain_signature_terms.join(" "),
                bp.domain_probe_ko,
                bp.domain_probe_en,
            );
            check_citizen_text(&combined, &[]).unwrap_or_else(|e| {
                panic!("CITIZEN_FORBIDDEN_TERM found in blueprint {}: {e:?}", bp.domain_id)
            });
            assert!(
                !contains_forbidden_raw_gov_id_digits(&combined),
                "forbidden gov id digits in blueprint {}",
                bp.domain_id
            );
        }
    }
}
